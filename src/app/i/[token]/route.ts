/**
 * GET /i/[token] — the secret-link image surface.
 *
 * A route handler, not a page: the response is the raw image bytes and
 * nothing else. No HTML shell, no navbar, no footer, no title, no owner
 * identity — opening the URL in a browser renders exactly the image, and
 * embedding it in an <img src> works directly. Possession of the unguessable
 * 256-bit token IS the access control; there is no listing, sitemap entry,
 * or on-platform link to any /i/<token> URL.
 *
 * Response hardening:
 * - X-Robots-Tag: noindex, nofollow — if a secret URL is ever pasted onto a
 *   public page, search engines are told to ignore it.
 * - Cache-Control: private — browsers may cache the immutable bytes, but
 *   shared/CDN caches must not.
 * - Content-Disposition: inline — renders in the browser rather than
 *   downloading.
 * - 404s are plain text: even the error path carries no chrome.
 */

import { NextRequest, NextResponse } from "next/server";
import path from "node:path";
import fsp from "node:fs/promises";
import { createReadStream } from "node:fs";
import { Readable } from "node:stream";
import { prisma } from "@/lib/db";
import { isValidImageToken } from "@/lib/images";
import { UPLOADS_DIR, SECRET_UPLOADS_DIR } from "@/lib/uploads";

// Only the extensions lib/uploads.ts can produce — the stored extension is
// derived from the validated MIME allowlist, never from a user filename.
const MIME_TYPES: Record<string, string> = {
  ".jpg": "image/jpeg",
  ".png": "image/png",
  ".gif": "image/gif",
  ".webp": "image/webp",
};

export async function GET(
  _request: NextRequest,
  { params }: { params: Promise<{ token: string }> }
) {
  const { token } = await params;

  // Shape-check before the database: garbage tokens (probing, traversal
  // attempts, old broken links) are refused without a query.
  if (!isValidImageToken(token)) {
    return new NextResponse("Not found", { status: 404 });
  }

  const published = await prisma.publishedImage.findUnique({ where: { token } });
  if (!published) {
    return new NextResponse("Not found", { status: 404 });
  }

  // Defense in depth: filenames are system-generated by lib/uploads.ts, but
  // the read path still refuses anything outside the image directories.
  // PHASE_47 (audit S1): published images live in data/uploads/secret/, an
  // isolated directory the public /api/uploads route can never reach. Files
  // stored before PHASE_47 are resolved from the legacy data/uploads/ location
  // — still unreachable publicly, because /api/uploads serves only filenames
  // referenced by an existing Tool.imageUrl.
  const safeFilename = path.basename(published.filename);
  const secretPath = path.resolve(SECRET_UPLOADS_DIR, safeFilename);
  const legacyPath = path.resolve(UPLOADS_DIR, safeFilename);
  // PHASE_53 (audit P1): async fs on the hot path — no synchronous stat/read.
  const resolveExisting = async (candidate: string, base: string): Promise<string | null> =>
    candidate.startsWith(base + path.sep) &&
    (await fsp
      .stat(candidate)
      .then((s) => s.isFile())
      .catch(() => false))
      ? candidate
      : null;
  const filePath =
    (await resolveExisting(secretPath, SECRET_UPLOADS_DIR)) ??
    (await resolveExisting(legacyPath, UPLOADS_DIR));
  if (!filePath) {
    return new NextResponse("Not found", { status: 404 });
  }

  const contentType = MIME_TYPES[path.extname(safeFilename).toLowerCase()];
  if (!contentType) {
    // Unreachable via the create route (allowlist-derived extensions only);
    // refuse to guess rather than serve an unknown type.
    return new NextResponse("Not found", { status: 404 });
  }

  const fileStat = await fsp.stat(filePath);

  return new NextResponse(Readable.toWeb(createReadStream(filePath)) as unknown as ReadableStream, {
    headers: {
      "Content-Type": contentType,
      "Content-Length": String(fileStat.size),
      "Content-Disposition": "inline",
      "Cache-Control": "private, max-age=31536000, immutable",
      "X-Robots-Tag": "noindex, nofollow",
      // PHASE_49 (audit S8): never MIME-sniff the response into execution.
      // (The global CSP from next.config.ts also applies to this route —
      // next.config headers() override a route-level CSP of the same name —
      // so the sandboxing CSP is deliberately set there, once, app-wide.)
      "X-Content-Type-Options": "nosniff",
    },
  });
}
